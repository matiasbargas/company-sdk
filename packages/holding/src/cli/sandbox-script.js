'use strict';

/**
 * cli/sandbox-script.js — the D7 setup script `sdk-holding sandbox setup` writes for the Owner to
 * review and run with sudo. Pure: every input is validated to be shell- and sudoers-safe, and the
 * tool never runs the script. See cli/sandbox.js for the command and sandbox-access.js for the
 * reachability rules the runtime step satisfies.
 */

const { refuse } = require('./common');

const SAFE_PATH_RE = /^\/[A-Za-z0-9._/+-]+$/;   // sudoers and sh-safe without quoting games
const SAFE_NAME_RE = /^[A-Za-z_][A-Za-z0-9._-]{0,31}$/;

/** The reviewed setup script (pure: every input is validated to be shell- and sudoers-safe). */
function generateSetupScript({ user, home, sessionDir, owner, holdingDir, companyDir, claudeBin, runtimeDir, hookSrc, nodePath, nodeSrc }) {
  const paths = { home, sessionDir, holdingDir, companyDir, claudeBin, runtimeDir, hookSrc, nodePath };
  if (nodeSrc) paths.nodeSrc = nodeSrc;
  for (const [k, v] of Object.entries(paths)) {
    if (typeof v !== 'string' || !SAFE_PATH_RE.test(v) || v.split('/').includes('..')) {
      refuse(`${k} ${JSON.stringify(v)} must be an absolute path of letters, digits and . _ / + - only (it goes into sudoers)`);
    }
  }
  for (const [k, v] of Object.entries({ user, owner })) {
    if (typeof v !== 'string' || !SAFE_NAME_RE.test(v)) refuse(`${k} ${JSON.stringify(v)} is not a valid account name`);
  }
  const sessions = sessionDir;
  return `#!/bin/sh
# sdk-holding sandbox setup — GENERATED by sdk-holding; REVIEW EVERY LINE, then run: sudo sh <this file>
# Owner decision D7 (2026-11-15): company sessions run as a dedicated, unprivileged OS user.
#   sandbox user : ${user}   home: ${home}   session dir: ${sessionDir} (Owner-owned 0755)
#   Owner        : ${owner}
#   holding/     : ${holdingDir}   (Owner only, 0700: ledger, keys, settings, freeze flag)
#   company clone: ${companyDir}   (owned by ${user}; the Owner reads it through group ${user})
#   claude       : ${claudeBin}   (the ONLY command the Owner may run as ${user})
#   hook runtime : ${runtimeDir}   (Owner-owned 0755: node ${nodePath} + landing-hook.js, reachable by ${user})
set -eu

SANDBOX_USER='${user}'
SANDBOX_GROUP='${user}'
SANDBOX_HOME='${home}'
SESSIONS_DIR='${sessions}'
OWNER='${owner}'
HOLDING_DIR='${holdingDir}'
COMPANY_DIR='${companyDir}'
CLAUDE_BIN='${claudeBin}'
RUNTIME_DIR='${runtimeDir}'
HOOK_SRC='${hookSrc}'
NODE_PATH='${nodePath}'
${nodeSrc ? `NODE_SRC='${nodeSrc}'\n` : ''}DROPIN="/etc/sudoers.d/sdk-holding-\${SANDBOX_USER}"

[ "$(id -u)" -eq 0 ] || { echo "run this with sudo" >&2; exit 1; }
[ "$(uname -s)" = Darwin ] || { echo "macOS only (uses dscl)" >&2; exit 1; }
[ -x "$CLAUDE_BIN" ] || { echo "claude not found at $CLAUDE_BIN" >&2; exit 1; }
id "$OWNER" >/dev/null 2>&1 || { echo "no such Owner account $OWNER" >&2; exit 1; }

# Highest id in the 400-499 service range, or 400.
last_id() { dscl . -list "$1" "$2" | awk '$2 >= 400 && $2 < 500 { print $2 }' | sort -n | tail -1; }

# 1. A dedicated group and a hidden user with no login shell (not in staff, not an admin).
if ! dscl . -read "/Groups/$SANDBOX_GROUP" >/dev/null 2>&1; then
  n=$(last_id /Groups PrimaryGroupID); gid=$(( \${n:-400} + 1 ))
  dscl . -create "/Groups/$SANDBOX_GROUP"
  dscl . -create "/Groups/$SANDBOX_GROUP" PrimaryGroupID "$gid"
  dscl . -create "/Groups/$SANDBOX_GROUP" RealName "sdk-holding sandbox"
fi
gid=$(dscl . -read "/Groups/$SANDBOX_GROUP" PrimaryGroupID | awk '{ print $2 }')
if ! dscl . -read "/Users/$SANDBOX_USER" >/dev/null 2>&1; then
  n=$(last_id /Users UniqueID); uid=$(( \${n:-400} + 1 ))
  dscl . -create "/Users/$SANDBOX_USER"
  dscl . -create "/Users/$SANDBOX_USER" UniqueID "$uid"
  dscl . -create "/Users/$SANDBOX_USER" PrimaryGroupID "$gid"
  dscl . -create "/Users/$SANDBOX_USER" UserShell /usr/bin/false
  dscl . -create "/Users/$SANDBOX_USER" NFSHomeDirectory "$SANDBOX_HOME"
  dscl . -create "/Users/$SANDBOX_USER" RealName "sdk-holding sandbox"
  dscl . -create "/Users/$SANDBOX_USER" IsHidden 1
fi

# 2. Its home (private to it).
mkdir -p "$SANDBOX_HOME"
chown "$SANDBOX_USER:$SANDBOX_GROUP" "$SANDBOX_HOME"
chmod 700 "$SANDBOX_HOME"

# 3. Session files: Owner-owned 0755, so the sandbox user can read its per-run settings but never write them.
mkdir -p "$SESSIONS_DIR"
chown "$OWNER" "$SESSIONS_DIR"
chmod 755 "$SESSIONS_DIR"

# 4. The company clone belongs to the sandbox user; the Owner keeps read access through the group.
chown -R "$SANDBOX_USER:$SANDBOX_GROUP" "$COMPANY_DIR"
chmod -R u+rwX,g+rX,o-rwx "$COMPANY_DIR"
dseditgroup -o edit -a "$OWNER" -t user "$SANDBOX_GROUP"

# 5. The holding control plane: the Owner only.
chown -R "$OWNER" "$HOLDING_DIR"
chmod 700 "$HOLDING_DIR"

# 6. sudoers drop-in: ONLY this claude path, as this user, without a password; the environment is
#    reset except ANTHROPIC_API_KEY and HOLDING_RUN_ID (no SETENV). Validated before install.
TMP=$(mktemp /tmp/sdk-holding-sudoers.XXXXXX)
cat > "$TMP" <<EOF
Defaults!$CLAUDE_BIN env_keep += "ANTHROPIC_API_KEY HOLDING_RUN_ID"
$OWNER ALL=($SANDBOX_USER) NOPASSWD: $CLAUDE_BIN
EOF
visudo -cf "$TMP"
install -m 0440 -o root -g wheel "$TMP" "$DROPIN"
rm -f "$TMP"

# 7. The landing/freeze hook runtime, where the sandbox user can exec it. A PreToolUse hook that
#    cannot run exits non-zero, which Claude Code treats as NON-blocking: landing and freeze would
#    fail OPEN. landing-hook.js is self-contained (node built-ins only).
mkdir -p "$RUNTIME_DIR"
chown "$OWNER" "$RUNTIME_DIR"
chmod 755 "$RUNTIME_DIR"
install -m 0644 -o "$OWNER" "$HOOK_SRC" "$RUNTIME_DIR/landing-hook.js"
${nodeSrc ? `# node: no world-traversable node was found, so a copy is installed next to the hook.
install -m 0755 -o "$OWNER" "$NODE_SRC" "$NODE_PATH"
` : `# node: $NODE_PATH is already world-traversable (every parent o+x); nothing copied.
`}
# 8. Prove it as the sandbox user (not just by mode bits): node, hook, claude, clone, session dir.
sudo -u "$SANDBOX_USER" /bin/test -x "$NODE_PATH" || { echo "$SANDBOX_USER cannot exec $NODE_PATH" >&2; exit 1; }
sudo -u "$SANDBOX_USER" /bin/test -r "$RUNTIME_DIR/landing-hook.js" || { echo "$SANDBOX_USER cannot read the hook" >&2; exit 1; }
sudo -u "$SANDBOX_USER" /bin/test -x "$CLAUDE_BIN" || { echo "$SANDBOX_USER cannot exec $CLAUDE_BIN (move claude to a traversable path)" >&2; exit 1; }
sudo -u "$SANDBOX_USER" /bin/test -w "$COMPANY_DIR" || { echo "$SANDBOX_USER cannot write $COMPANY_DIR (a parent is not traversable?)" >&2; exit 1; }
sudo -u "$SANDBOX_USER" /bin/test -r "$SESSIONS_DIR" || { echo "$SANDBOX_USER cannot read $SESSIONS_DIR" >&2; exit 1; }

# 9. Prove the installed hook DENIES as $SANDBOX_USER (Guardian N1). Reachable is not enough: a hook that
#    runs but stays silent lets a landing session keep writing. A synthetic landing state, one Write:
#    the hook must answer permissionDecision "deny", or this script stops here and names why.
# --- hook probe (begin)
PROBE_DIR=$(mktemp -d /tmp/sdk-holding-probe.XXXXXX)
trap 'rm -rf "$PROBE_DIR"' EXIT
chmod 755 "$PROBE_DIR"
cat > "$PROBE_DIR/state.json" <<EOF
{"run_id":"setup-probe","budget_fu":1,"spent_fu":1,"estimate":true,"landing":true,"landing_reason":"sandbox setup probe","freeze_flag":"$PROBE_DIR/FROZEN","status_files":["current-status.md"]}
EOF
chmod 644 "$PROBE_DIR/state.json"
PROBE_IN='{"hook_event_name":"PreToolUse","tool_name":"Write","tool_input":{"file_path":"/tmp/sdk-holding-probe-target","content":"x"}}'
if ! PROBE_OUT=$(cd / && printf '%s' "$PROBE_IN" | sudo -u "$SANDBOX_USER" "$NODE_PATH" "$RUNTIME_DIR/landing-hook.js" --state "$PROBE_DIR/state.json" 2>"$PROBE_DIR/stderr"); then
  echo "ABORT: the installed hook could not run as $SANDBOX_USER ($NODE_PATH $RUNTIME_DIR/landing-hook.js): $(head -c 400 "$PROBE_DIR/stderr" 2>/dev/null)" >&2
  echo "       Claude Code treats a hook that fails as non-blocking, so landing and freeze would fail OPEN." >&2
  exit 1
fi
case "$PROBE_OUT" in
  *'"permissionDecision":"deny"'*) echo "ok: the installed hook denies a Write in landing mode as $SANDBOX_USER" ;;
  *) echo "ABORT: the installed hook ran as $SANDBOX_USER but did NOT deny a Write in landing mode (output: \${PROBE_OUT:-<empty>})." >&2
     echo "       $RUNTIME_DIR/landing-hook.js is not the landing hook sdk-holding ships: rerun sdk-holding sandbox setup, then this script." >&2
     exit 1 ;;
esac
# --- hook probe (end)

echo "sandbox ready for $SANDBOX_USER."
echo "As $OWNER (not root): git config --global --add safe.directory $COMPANY_DIR"
echo "Then check everything: sdk-holding sandbox doctor"
`;
}

module.exports = { generateSetupScript, SAFE_PATH_RE };
