#!/usr/bin/env node

/**
 * gen-agents.js — generate Claude Code subagent definitions (.claude/agents/*.md).
 *
 * One subagent per role file in team/roles/, plus the fresh-context loop roles (critic,
 * judge, red-teamer, blind-synthesizer). The role file stays the single source of
 * persona; the generated body only says which files to read and what authority the
 * spawn has. Tool lists make the protocol's written rules enforced:
 *   - consultation peers (§16) are READ ONLY → Read, Grep, Glob
 *   - Guardians (§31.6) review and record verdicts → + Bash (for `sdk-doc iteration`)
 *   - Loop Coordinator (§32.1) writes loop state → + Bash, Write
 *   - Engineer / Test Engineer are execution assignments (§16 tier 2) → full edit tools,
 *     scoped by the spawn prompt; they still never commit/merge unless instructed
 *
 *   node scripts/gen-agents.js           write .claude/agents/
 *   node scripts/gen-agents.js --check   exit 1 if any generated file is stale (npm test)
 */

'use strict';

const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const rolesDir = path.join(root, 'team', 'roles');
const outDir = path.join(root, '.claude', 'agents');
const BANNER = '<!-- GENERATED by scripts/gen-agents.js from team/roles/ — do not edit; edit the role file. -->';

const READ_ONLY = 'Read, Grep, Glob';
const TOOLS = {
  'discovery-guardian': `${READ_ONLY}, Bash`,
  'architecture-guardian': `${READ_ONLY}, Bash`,
  'implementation-guardian': `${READ_ONLY}, Bash`,
  'loop-coordinator': `${READ_ONLY}, Bash, Write`,
  engineer: `${READ_ONLY}, Bash, Edit, Write`,
  'test-engineer': `${READ_ONLY}, Bash, Edit, Write`,
};
const EXECUTION = new Set(['engineer', 'test-engineer']);

function field(text, label) {
  const m = text.match(new RegExp(`^\\*\\*${label}:\\*\\*\\s*(.+)$`, 'm'));
  return m ? m[1].trim() : '';
}

function title(text, slug) {
  const m = text.match(/You are \*\*\{\{name\}\}\*\*,\s*(?:the\s+|an?\s+)?([^.]+?)\s+(?:of|at)\s+\{\{company\}\}/);
  return m ? m[1].trim() : slug;
}

function clip(s, n) {
  return s.length > n ? s.slice(0, n - 1).replace(/\s+\S*$/, '') + '…' : s;
}

function roleAgent(file) {
  const slug = path.basename(file, '.md');
  const text = fs.readFileSync(path.join(rolesDir, file), 'utf8');
  const t = title(text, slug);
  const answers = field(text, 'Answers');
  const when = field(text, 'Consult me when');
  const description = clip(`team-sdk ${t}. ${answers ? `Answers: ${answers}.` : ''} ${when ? `Consult when: ${when}` : ''}`.replace(/\s+/g, ' ').trim(), 480)
    .replace(/"/g, "'");
  const tools = TOOLS[slug] || READ_ONLY;
  const isGuardian = slug.endsWith('-guardian');
  const isLoop = slug === 'loop-coordinator';

  const authority = EXECUTION.has(slug)
    ? 'This is an execution assignment (`protocol.md` §16, write tier). Change only the files in the scope your spawn prompt assigns. Run the tests you touched and report the command and pass counts. Never commit, merge, or push unless the EM or the Owner told you to in the spawn prompt.'
    : isGuardian
    ? 'You have REVIEW authority only (`protocol.md` §31.6 and `team/roles/_guardian.md`). The only writes you make are through `sdk-doc iteration` on your own loop. Never edit requirements files, area logs, or `history.md`.'
    : isLoop
      ? 'You are the driver, not the judge (`protocol.md` §32.1). Write only the loop state under `record/loops/<id>/` and Bus transitions. Never give a content opinion.'
      : 'You were spawned for consultation or review, so you are READ ONLY (`protocol.md` §16): no project writes and no `sdk-doc` write commands. If the task needs writes, say so and return a proposed change for the spawning agent to apply.';

  return `---
name: ${slug}
description: "${description}"
tools: ${tools}
omitClaudeMd: true
---
${BANNER}

You are the **${t}** in the team-sdk company, running as a subagent.

1. Read \`team/roles/_shared.md\`${isGuardian ? ', then `team/roles/_guardian.md`,' : ''} then \`team/roles/${file}\`. Adopt that persona exactly. Do not take any other persona from the conversation, including Greg's, unless you are the CEO.
2. Fill \`{{name}}\`, \`{{city}}\`, \`{{cultural_profile}}\` and \`{{company}}\` from your spawn prompt. If they are missing, follow \`_shared.md\` → Placeholders.
3. Load context per \`protocol.md\` §7, and only what this task needs.
4. ${authority}
5. Return a synthesis, not raw notes. For a consultation, use the \`peer-consult\` return shape: role, sub_question, insight, confidence, assumption_that_flips_it, sources.
`;
}

// Fresh-context loop roles (§32): independence from the author is structural, not requested.
const LOOP_AGENTS = {
  critic: {
    description: 'Fresh-context critic for a §32 Critique-Revise loop. Reads a draft against the constitution and returns sourced critique records plus the would-have-wrongly-killed line. Never the author.',
    body: `Follow \`team/roles/loops/critique-revise.md\` → Mechanism steps 2–3.
- Return one record per critique: \`{clause_id, quote_from_draft, violation, proposed_fix, severity}\`. A record with no clause or no quote is invalid, so do not emit it.
- Then emit \`would-have-wrongly-killed: <bold property the critique does not damage>\` (§32.3). The loop fails closed without it.
- You do not revise the draft, and you do not judge convergence.`,
  },
  judge: {
    description: 'Fresh-context judge for a §32 Critique-Revise loop. Scores a revision against the critique records with the rubric (resolved/partially/unresolved + guardrail preserved). Never the critic or author.',
    body: `Follow \`team/roles/loops/critique-revise.md\` → Mechanism step 5.
- For each critique record, score the revision resolved / partially / unresolved, and quote the revised text.
- Score whether the \`would-have-wrongly-killed\` property is preserved (yes / no).
- Verdict: SHIP only if every record is resolved AND preserved = yes. Otherwise NO-SHIP, and list the gaps. Do not propose a new draft.`,
  },
  'red-teamer': {
    description: 'Fresh-context red-teamer for a §32 Red-Team loop. Attacks a plan or decision from another domain and returns the ONE killing assumption plus the assumption-not-attacked line.',
    body: `Follow \`team/roles/loops/red-team.md\` → Mechanism.
- Return exactly ONE assumption: the one that, if false, kills the plan. Give the evidence, the failure scenario, and a severity.
- Emit \`assumption-not-attacked: <what you deliberately did not test>\` (alias \`red-team-scope-limit:\`). The result is void without it.
- No mitigation essay. The spawning agent decides what to do.`,
  },
  'blind-synthesizer': {
    description: 'Fresh-context synthesizer for a Dialectic loop (v0.2). Receives only anonymized proposals A/B and scores each constraint honored/traded/dropped. Never sees role identities.',
    body: `Follow \`team/roles/loops/dialectic.md\` → synthesis steps. You only ever receive anonymized proposals.
- If a proposal reveals its author's role, say so and stop. The anonymization failed.
- Score every stated constraint honored / traded / dropped, then propose one synthesis.
- Recommend another round only if a constraint was dropped (and \`limits.loopIterations\` allows it).`,
  },
};

function loopAgent(name, spec) {
  return `---
name: ${name}
description: "${spec.description.replace(/"/g, "'")}"
tools: ${READ_ONLY}
omitClaudeMd: true
---
${BANNER}

You are a fresh-context **${name}** in a team-sdk generative loop (\`protocol.md\` §32). You did not write the artifact under review, and you have no stake in it. Read \`team/roles/_shared.md\` (Constraints and Soul) first.

${spec.body}

READ ONLY: return your output to the spawning agent and the Loop Coordinator. Do not write files.
`;
}

function build() {
  const out = {};
  for (const f of fs.readdirSync(rolesDir).filter(n => n.endsWith('.md') && !n.startsWith('_') && n !== 'CLAUDE.md' && n !== 'CONSULT.md').sort()) {
    out[f] = roleAgent(f);
  }
  for (const [name, spec] of Object.entries(LOOP_AGENTS)) out[`${name}.md`] = loopAgent(name, spec);
  return out;
}

const files = build();
if (process.argv.includes('--check')) {
  const stale = Object.entries(files).filter(([f, c]) => {
    const p = path.join(outDir, f);
    return !fs.existsSync(p) || fs.readFileSync(p, 'utf8') !== c;
  }).map(([f]) => f);
  const orphans = fs.existsSync(outDir)
    ? fs.readdirSync(outDir).filter(f => f.endsWith('.md') && !files[f] && fs.readFileSync(path.join(outDir, f), 'utf8').includes(BANNER))
    : [];
  if (stale.length || orphans.length) {
    console.error(`✗ .claude/agents out of date (${[...stale, ...orphans.map(o => o + ' (orphan)')].join(', ')})\n  Run: node scripts/gen-agents.js`);
    process.exit(1);
  }
  console.log(`✓ .claude/agents matches team/roles (${Object.keys(files).length} agents)`);
} else {
  fs.mkdirSync(outDir, { recursive: true });
  for (const f of fs.readdirSync(outDir)) {
    const p = path.join(outDir, f);
    if (f.endsWith('.md') && !files[f] && fs.readFileSync(p, 'utf8').includes(BANNER)) fs.unlinkSync(p);
  }
  for (const [f, c] of Object.entries(files)) fs.writeFileSync(path.join(outDir, f), c, 'utf8');
  console.log(`✓ generated ${Object.keys(files).length} agents in .claude/agents/`);
}
