#!/usr/bin/env node

/**
 * split-protocol.js — regenerate protocol-core.md and protocol-reference.md from protocol.md.
 *
 * protocol.md is the only hand-edited source. The two views are byte-for-byte slices of it
 * (core = Sections 0-13, reference = Section 14 onward) under a generated header, so their
 * version can never drift from the source again.
 *
 *   node scripts/split-protocol.js           write both files
 *   node scripts/split-protocol.js --check   exit 1 if either file is stale (used by npm test)
 */

'use strict';

const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const SOURCE = path.join(root, 'protocol.md');
const CORE = path.join(root, 'protocol-core.md');
const REF = path.join(root, 'protocol-reference.md');
const SPLIT_AT = 14; // first section that goes to the reference view

function build(src) {
  const version = (src.match(/^\*\*Version:\*\*\s*(\S+)/m) || [])[1];
  if (!version) throw new Error('protocol.md has no **Version:** header');

  const lines = src.split('\n');
  const sectionStart = (n) => lines.findIndex(l => new RegExp(`^## ${n}\\.\\s`).test(l));
  const first = sectionStart(0);
  const split = sectionStart(SPLIT_AT);
  if (first === -1 || split === -1) throw new Error(`protocol.md is missing "## 0." or "## ${SPLIT_AT}."`);

  // Body ends before the closing "---\n\n*Protocol vX...*" footer.
  let end = lines.length;
  const footer = lines.findIndex(l => /^\*Protocol v/.test(l));
  if (footer !== -1) {
    end = footer;
    while (end > 0 && (lines[end - 1].trim() === '' || lines[end - 1].trim() === '---')) end--;
  }

  const trim = (arr) => {
    const a = arr.slice();
    while (a.length && (a[a.length - 1].trim() === '' || a[a.length - 1].trim() === '---')) a.pop();
    return a.join('\n');
  };

  const lastSection = (lines.slice(split, end).filter(l => /^## \d+\./.test(l)).pop() || '').match(/^## (\d+)\./);
  const refRange = `Sections ${SPLIT_AT}-${lastSection ? lastSection[1] : '?'}`;
  const banner = '<!-- GENERATED by scripts/split-protocol.js from protocol.md — do not edit. -->';

  const core = `${banner}
# Protocol -- Shared Interface Contract (Core)
**Version:** ${version}
**Owner:** Coordinator
**Every agent references this file. Do not duplicate these definitions in individual role files. If the protocol changes, it changes in protocol.md.**

> Sections 0-${SPLIT_AT - 1} of \`protocol.md\` — the sections agents need every session. ${refRange} live in \`protocol-reference.md\`.

---

${trim(lines.slice(first, split))}

---

*Protocol v${version} (core). Sections 0-${SPLIT_AT - 1}. Generated from protocol.md.*
`;

  const ref = `${banner}
# Protocol -- Shared Interface Contract (Reference)
**Version:** ${version}
**Owner:** Coordinator

> ${refRange} of \`protocol.md\` — loaded only when the topic requires them. Sections 0-${SPLIT_AT - 1} live in \`protocol-core.md\`.

---

${trim(lines.slice(split, end))}

---

*Protocol v${version} (reference). ${refRange}. Generated from protocol.md.*
`;

  return { core, ref };
}

const { core, ref } = build(fs.readFileSync(SOURCE, 'utf8'));

if (process.argv.includes('--check')) {
  const stale = [[CORE, core], [REF, ref]]
    .filter(([f, want]) => !fs.existsSync(f) || fs.readFileSync(f, 'utf8') !== want)
    .map(([f]) => path.basename(f));
  if (stale.length) {
    console.error(`✗ stale generated protocol view(s): ${stale.join(', ')}\n  Run: node scripts/split-protocol.js`);
    process.exit(1);
  }
  console.log('✓ protocol-core.md and protocol-reference.md match protocol.md');
} else {
  fs.writeFileSync(CORE, core, 'utf8');
  fs.writeFileSync(REF, ref, 'utf8');
  console.log('✓ regenerated protocol-core.md and protocol-reference.md from protocol.md');
}
