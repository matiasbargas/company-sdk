#!/usr/bin/env node

/**
 * @covers cap-sdk-views-001  (project/context/spec/sdk-core/claims.yaml)
 * split-protocol.js — regenerate protocol-core.md and protocol-reference.md from protocol.md.
 *
 * protocol.md is the only hand-edited source. Generated from it, byte-for-byte:
 *   - protocol-core.md (Sections 0-13) and protocol-reference.md (Section 14 onward)
 *   - protocol/NN-<slug>.md, one file per top-level section, plus protocol/INDEX.md
 *     (agents load one section by number instead of the 100+ KB whole)
 * so no view can drift from the source.
 *
 *   node scripts/split-protocol.js           write every view
 *   node scripts/split-protocol.js --check   exit 1 if any view is stale (used by npm test)
 */

'use strict';

const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const SOURCE = path.join(root, 'protocol.md');
const CORE = path.join(root, 'protocol-core.md');
const REF = path.join(root, 'protocol-reference.md');
const SECTIONS_DIR = path.join(root, 'protocol');
const SPLIT_AT = 14; // first section that goes to the reference view

function build(src) {
  const version = (src.match(/^\*\*Version:\*\*\s*(\S+)/m) || [])[1];
  if (!version) throw new Error('protocol.md has no **Version:** header');

  const lines = src.split('\n');
  const sectionStart = (n) => lines.findIndex(l => new RegExp(`^## ${n}\\.\\s`).test(l));
  const first = sectionStart(0);
  const split = sectionStart(SPLIT_AT);
  if (first === -1 || split === -1) throw new Error(`protocol.md is missing "## 0." or "## ${SPLIT_AT}."`);

  // Body ends before the closing "---\n\n*Protocol vX...*" footer.
  let end = lines.length;
  const footer = lines.findIndex(l => /^\*Protocol v/.test(l));
  if (footer !== -1) {
    end = footer;
    while (end > 0 && (lines[end - 1].trim() === '' || lines[end - 1].trim() === '---')) end--;
  }

  const trim = (arr) => {
    const a = arr.slice();
    while (a.length && (a[a.length - 1].trim() === '' || a[a.length - 1].trim() === '---')) a.pop();
    return a.join('\n');
  };

  const lastSection = (lines.slice(split, end).filter(l => /^## \d+\./.test(l)).pop() || '').match(/^## (\d+)\./);
  const refRange = `Sections ${SPLIT_AT}-${lastSection ? lastSection[1] : '?'}`;
  const banner = '<!-- GENERATED by scripts/split-protocol.js from protocol.md — do not edit. -->';

  const core = `${banner}
# Protocol -- Shared Interface Contract (Core)
**Version:** ${version}
**Owner:** Coordinator
**Every agent references this file. Do not duplicate these definitions in individual role files. If the protocol changes, it changes in protocol.md.**

> Sections 0-${SPLIT_AT - 1} of \`protocol.md\` — the sections agents need every session. ${refRange} live in \`protocol-reference.md\`.

---

${trim(lines.slice(first, split))}

---

*Protocol v${version} (core). Sections 0-${SPLIT_AT - 1}. Generated from protocol.md.*
`;

  const ref = `${banner}
# Protocol -- Shared Interface Contract (Reference)
**Version:** ${version}
**Owner:** Coordinator

> ${refRange} of \`protocol.md\` — loaded only when the topic requires them. Sections 0-${SPLIT_AT - 1} live in \`protocol-core.md\`.

---

${trim(lines.slice(split, end))}

---

*Protocol v${version} (reference). ${refRange}. Generated from protocol.md.*
`;

  // Per-section files: from each "## N." heading to the next one (or the body end).
  const starts = [];
  lines.forEach((l, i) => { const m = l.match(/^## (\d+)\.\s+(.*)$/); if (m && i < end) starts.push({ i, n: m[1], title: m[2] }); });
  const sections = {};
  const index = [];
  starts.forEach((st, k) => {
    const stop = k + 1 < starts.length ? starts[k + 1].i : end;
    const slug = st.title.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 48);
    const name = `${String(st.n).padStart(2, '0')}-${slug}.md`;
    const body = trim(lines.slice(st.i, stop));
    sections[name] = `<!-- GENERATED by scripts/split-protocol.js from protocol.md (v${version}) — do not edit. -->\n${body}\n`;
    index.push(`| §${st.n} | ${st.title.replace(/\|/g, '/')} | [${name}](${name}) | ${body.split('\n').length} |`);
  });
  sections['INDEX.md'] = `<!-- GENERATED by scripts/split-protocol.js from protocol.md — do not edit. -->
# Protocol v${version} — section index

Load one section by number (\`protocol/NN-*.md\`) instead of the whole of \`protocol.md\`. Sections 0–${SPLIT_AT - 1} are also bundled in \`protocol-core.md\`.

| § | Title | File | Lines |
|---|---|---|---|
${index.join('\n')}
`;

  return { core, ref, sections };
}

const { core, ref, sections } = build(fs.readFileSync(SOURCE, 'utf8'));
const targets = [[CORE, core], [REF, ref], ...Object.entries(sections).map(([n, c]) => [path.join(SECTIONS_DIR, n), c])];
const orphans = () => fs.existsSync(SECTIONS_DIR)
  ? fs.readdirSync(SECTIONS_DIR).filter(n => n.endsWith('.md') && !sections[n]).map(n => path.join(SECTIONS_DIR, n))
  : [];

if (process.argv.includes('--check')) {
  const stale = targets
    .filter(([f, want]) => !fs.existsSync(f) || fs.readFileSync(f, 'utf8') !== want)
    .map(([f]) => path.relative(root, f))
    .concat(orphans().map(f => path.relative(root, f) + ' (orphan)'));
  if (stale.length) {
    console.error(`✗ stale generated protocol view(s): ${stale.slice(0, 8).join(', ')}${stale.length > 8 ? ` … +${stale.length - 8}` : ''}\n  Run: node scripts/split-protocol.js`);
    process.exit(1);
  }
  console.log(`✓ protocol-core.md, protocol-reference.md and protocol/ (${Object.keys(sections).length} files) match protocol.md`);
} else {
  fs.mkdirSync(SECTIONS_DIR, { recursive: true });
  for (const f of orphans()) fs.unlinkSync(f);
  for (const [f, c] of targets) fs.writeFileSync(f, c, 'utf8');
  console.log(`✓ regenerated protocol-core.md, protocol-reference.md and protocol/ (${Object.keys(sections).length} files) from protocol.md`);
}
